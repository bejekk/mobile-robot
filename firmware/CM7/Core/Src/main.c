/* Telemetria: zadanie i pomiar [RPM] dla 4 kół, kolejność RB, RF, LB, LF. */
void UART_SendSpeeds(void)
{
	char msg[100];
	int len = sprintf(msg, "%ld, %ld, %ld, %ld, %ld, %ld, %ld, %ld\r\n",
			  (long)right_back.target_speed,
			  (long)right_back.filtered_speed,
			  (long)right_front.target_speed,
			  (long)right_front.filtered_speed,
			  (long)left_back.target_speed,
			  (long)left_back.filtered_speed,
			  (long)left_front.target_speed,
			  (long)left_front.filtered_speed);
	HAL_UART_Transmit(&huart3, (uint8_t *)msg, len, 10);	/* UART3 → Jetson / PC */
}

static int buzzer_tick = 0;

void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
	/* TIM13: pętla 10 ms — buzzer po "ready", PI i PWM kół DC. */
	if (htim->Instance == TIM13) {
		/* Krótki impuls buzzera (~0,5 s) po starcie pętli regulacji. */
		if (buzzer_tick < 50) {
			HAL_GPIO_WritePin(GPIOD, GPIO_PIN_6, GPIO_PIN_SET);
			buzzer_tick++;
		} else if (buzzer_tick < 60) {
			HAL_GPIO_WritePin(GPIOD, GPIO_PIN_6, GPIO_PIN_RESET);
			buzzer_tick = 100;
		}

		DC_update_speed(&right_front);
		DC_update_speed(&left_front);
		DC_update_speed(&right_back);
		DC_update_speed(&left_back);

		static uint8_t uart_div = 0;
		if (++uart_div >= 10) {		/* 10 × 10 ms = 100 ms telemetrii */
			UART_SendSpeeds();
			uart_div = 0;
		}

		int16_t out_rf = PI_Compute(&right_front);
		int16_t out_rb = PI_Compute(&right_back);
		int16_t out_lf = PI_Compute(&left_front);
		int16_t out_lb = PI_Compute(&left_back);

		/* Skalowanie wyjścia PI do zakresu PWM mostka (0…100). */
		fright_motor(((float)out_rf / right_front.max_speed) * 100);
		bright_motor(((float)out_rb / right_back.max_speed) * 100);
		fleft_motor(((float)out_lf / left_front.max_speed) * 100);
		bleft_motor(((float)out_lb / left_back.max_speed) * 100);
	}

	/* TIM6/7/14/15: impuls STEP na A4988 + zliczanie kroków. */
	if (htim->Instance == TIM6) {
		HAL_GPIO_TogglePin(GPIOG, GPIO_PIN_6);
		if (forward) {
			steps_bleft++;
		} else {
			steps_bleft--;
		}
	}
	if (htim->Instance == TIM7) {
		HAL_GPIO_TogglePin(GPIOG, GPIO_PIN_14);
		if (forward) {
			steps_bright++;
		} else {
			steps_bright--;
		}
	}
	if (htim->Instance == TIM15) {
		HAL_GPIO_TogglePin(GPIOC, GPIO_PIN_8);
		if (forward) {
			steps_fright++;
		} else {
			steps_fright--;
		}
	}
	if (htim->Instance == TIM14) {
		HAL_GPIO_TogglePin(GPIOC, GPIO_PIN_10);
		if (forward) {
			steps_fleft++;
		} else {
			steps_fleft--;
		}
	}
}

void parse_command(char command[50])
{
	static bool ready = false;

	/* Bez "ready" pętla PI nie startuje — zabezpieczenie przed jazdą tuż po resecie USB. */
	if (strcmp(command, "ready") == 0) {
		HAL_TIM_Base_Start_IT(&htim13);
		ready = true;
	}

	if (ready) {
		/* *_step przełącza, czy dany silnik krokowy ma jechać przy forward/backward. */
		if (strcmp(command, "fright_step") == 0) {
			fright = !fright;
		} else if (strcmp(command, "fleft_step") == 0) {
			fleft = !fleft;
		} else if (strcmp(command, "bleft_step") == 0) {
			bleft = !bleft;
		} else if (strcmp(command, "bright_step") == 0) {
			bright = !bright;
		}

		if (strcmp(command, "forward") == 0) {
			stepper_control(bleft, GPIOG, GPIO_PIN_7, 1, &htim6, GPIOG, GPIO_PIN_8);
			stepper_control(bright, GPIOD, GPIO_PIN_1, 1, &htim7, GPIOD, GPIO_PIN_10);
			stepper_control(fright, GPIOC, GPIO_PIN_9, 1, &htim15, GPIOB, GPIO_PIN_8);
			stepper_control(fleft, GPIOC, GPIO_PIN_11, 1, &htim14, GPIOB, GPIO_PIN_9);
		} else if (strcmp(command, "backward") == 0) {
			stepper_control(bleft, GPIOG, GPIO_PIN_7, 0, &htim6, GPIOG, GPIO_PIN_8);
			stepper_control(bright, GPIOD, GPIO_PIN_1, 0, &htim7, GPIOD, GPIO_PIN_10);
			stepper_control(fright, GPIOC, GPIO_PIN_9, 0, &htim15, GPIOB, GPIO_PIN_8);
			stepper_control(fleft, GPIOC, GPIO_PIN_11, 0, &htim14, GPIOB, GPIO_PIN_9);
		} else if (strcmp(command, "stop") == 0) {
			stepper_control(0, GPIOG, GPIO_PIN_7, 0, &htim6, GPIOG, GPIO_PIN_8);
			stepper_control(0, GPIOD, GPIO_PIN_1, 0, &htim7, GPIOD, GPIO_PIN_10);
			stepper_control(0, GPIOC, GPIO_PIN_9, 0, &htim15, GPIOB, GPIO_PIN_8);
			stepper_control(0, GPIOC, GPIO_PIN_11, 0, &htim14, GPIOB, GPIO_PIN_9);
		}

		/* lspeed/rspeed w % max RPM, ta sama wartość na koła przednie i tylne danej burty. */
		if (strncmp(command, "lspeed=", 7) == 0) {
			if (sscanf(command, "lspeed=%d", &Lvel) == 1) {
				left_front.target_speed = (left_front.max_speed / 100) * Lvel;
				left_back.target_speed = (left_back.max_speed / 100) * Lvel;
			}
		}
		if (strncmp(command, "rspeed=", 7) == 0) {
			if (sscanf(command, "rspeed=%d", &Rvel) == 1) {
				right_front.target_speed = (right_front.max_speed / 100) * Rvel;
				right_back.target_speed = (right_back.max_speed / 100) * Rvel;
			}
		}
	}

	/* P= i I= działają też przed ready — wygodne przy strojeniu z MATLABa. */
	if (strncmp(command, "P=", 2) == 0) {
		if (sscanf(command, "P=%d", &Kp) == 1) {
			right_front.Kp = (float)Kp;
			left_front.Kp = (float)Kp;
			right_back.Kp = (float)Kp;
			left_back.Kp = (float)Kp;
		}
	}
	if (strncmp(command, "I=", 2) == 0) {
		if (sscanf(command, "I=%d", &Ki) == 1) {
			right_front.Ki = (float)Ki;
			left_front.Ki = (float)Ki;
			right_back.Ki = (float)Ki;
			left_back.Ki = (float)Ki;
		}
	}
}

